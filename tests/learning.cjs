const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const canvas = page.frameLocator('#canvas');
  const operation = page.locator('#operation-explanation'), lesson = page.locator('#line-explanation');
  const results = path.resolve(__dirname, '../test-results');
  fs.mkdirSync(results, { recursive: true });
  try {
    await page.goto(process.env.BUILDER_URL);
    await canvas.locator('#root').waitFor();
    await page.locator('[data-component="section"]').click();
    assert.match(await operation.textContent(), /新增.*內容區塊/);
    await page.locator('[data-panel="css"]').click();
    const display = page.locator('[data-field="display"]');
    await display.selectOption('flex');
    assert.match(await operation.textContent(), /Flex.*橫向排列/);
    assert.match(await operation.textContent(), /display: flex;/);
    assert.match(await page.locator('#code-section-title').textContent(), /CSS 原始碼/);
    const code = page.locator('#source-code');
    const flexLine = code.locator('.code-line').filter({ hasText: /^\s*display: flex;/ });
    await flexLine.click();
    assert.match(await lesson.textContent(), /冒號.*分號/);
    assert.match(await lesson.textContent(), /#el-/);
    assert.equal(await code.locator('.explained-line').count(), 1);
    const height = code.locator('.code-line').filter({ hasText: /^\s*min-height: 90px;/ });
    await height.click();
    assert.match(await page.locator('#line-lesson-title').textContent(), /最小高度/);
    assert.match(await lesson.textContent(), /內容.*撐高/);
    // CSS selecting a different block must select its canvas owner too.
    await code.locator('.code-line').filter({ hasText: /^#root \{/ }).click();
    assert.equal(await page.locator('#selected-id').textContent(), '#root');
    assert.equal(await canvas.locator('#root').getAttribute('data-builder-selected'), '');
    await page.locator('[data-code="html"]').click();
    await code.locator('[data-code-node]').filter({ hasText: /section/ }).click();
    assert.match(await lesson.textContent(), /id=.*識別名稱/);
    const htmlLine = code.locator('.explained-line');
    await htmlLine.focus();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Enter');
    assert.match(await page.locator('#line-lesson-title').textContent(), /HTML 第/);
    // Undo should describe the reversed style change, not the now-stale operation.
    await page.locator('#undo').click();
    assert.match(await operation.textContent(), /復原/);
    assert.match(await operation.textContent(), /flex.*已移除/);
    await page.locator('#redo').click();
    assert.match(await operation.textContent(), /重做/);
    assert.match(await operation.textContent(), /display: flex;/);
    await page.locator('#demo').click();await page.locator('[data-template="sidebar"]').click();
    await page.locator('[data-code="js"]').click();
    await code.locator('.code-line').filter({ hasText: /target.hidden = !target.hidden;/ }).click();
    assert.match(await lesson.textContent(), /false → !false → true/);
    assert.match(await lesson.textContent(), /動作目標：nav/);
    await code.locator('.code-line').filter({ hasText: /const inputValue/ }).click();
    assert.match(await lesson.textContent(), /三元運算.*trim/);
    await code.locator('.code-line').filter({ hasText: /if \(inputValue ===/ }).click();
    assert.match(await lesson.textContent(), /比較.*指定/);
    await page.locator('[data-code="css"]').click();
    assert.match(await code.textContent(), /\/\* 元件 #.*桌面基本樣式 \*\//);
    // Explanation data is UI-only; project JSON keeps its existing schema.
    const promise = page.waitForEvent('download');await page.locator('#save-project').click();
    const download = await promise, projectFile = path.join(results, 'learning-project.json');
    await download.saveAs(projectFile);
    const project = JSON.parse(fs.readFileSync(projectFile, 'utf8'));
    assert.deepEqual(Object.keys(project).sort(), ['name', 'root', 'version']);
    await page.locator('#source-code .code-line').filter({ hasText: /^\s*flex: 0 0 220px;/ }).click();
    assert.match(await lesson.textContent(), /放大比例.*縮小比例.*基準尺寸/);
    await page.screenshot({ path: path.join(results, 'learning-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(results, 'learning-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS operation explanations, CSS values and syntax, HTML/CSS/JS clickable lines, canvas links, keyboard navigation, undo/redo lessons, CSS headings, unchanged JSON schema, mobile layout');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
